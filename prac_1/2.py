x = int(input("Введите целое число: "))

# 1. Чётность
if x % 2 == 0:
    print(f"{x} — чётное")
else:
    print(f"{x} — нечётное")

# 2. Знак
if x > 0:
    print(f"{x} — положительное")
elif x < 0:
    print(f"{x} — отрицательное")
else:
    print(f"{x} — ноль")

# 3. Диапазон [10, 50]
if 10 <= x <= 50:
    print(f"{x} принадлежит диапазону [10, 50]")
else:
    print(f"{x} не принадлежит диапазону [10, 50]")